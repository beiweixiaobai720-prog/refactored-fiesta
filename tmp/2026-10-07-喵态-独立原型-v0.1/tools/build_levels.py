def towers(spec, asleep=True):
    """竖着叠起来的睡猫塔：spec = [(x, n), ...]，底座在地面上（或给定 base）"""
    out = []
    for item in spec:
        x, n = item[0], item[1]
        base = item[2] if len(item) > 2 else 640
        for i in range(n):
            out.append([x + (1.0 if i % 2 else -1.0), base - R - 30 * i] + (["s"] if asleep else []))
    return out


def scatter(x0, x1, y, n, rows=1, asleep=False):
    """在 [x0, x1] 之间铺开 n 只猫，自下而上一层层放（互不重叠，六角错开）"""
    out = []
    per = max(1, int((x1 - x0) // 31))
    i = 0
    r = 0
    while i < n:
        off = 15 if r % 2 else 0
        cnt = per - (1 if r % 2 else 0)
        for c in range(cnt):
            if i >= n:
                break
            out.append([x0 + 15 + off + c * 31, y - r * 27] + (["s"] if asleep else []))
            i += 1
        r += 1
    return out


def hexpile(x_left, base, rows, asleep=True):
    """从左往右排的六角堆：rows = 每行只数（自下而上），每行起点右移半只猫"""
    out = []
    for r, n in enumerate(rows):
        y = base - R - r * 26
        for i in range(n):
            out.append([x_left + r * 15 + i * 30, y] + (["s"] if asleep else []))
    return out


